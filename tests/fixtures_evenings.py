import datetime as dt
from zoneinfo import ZoneInfo

TZ = ZoneInfo('Europe/London')


def ts(s: str) -> float:
    return dt.datetime.fromisoformat(s).replace(tzinfo=TZ).timestamp()


def series(day: str, rows: str) -> list[tuple[float, float]]:
    return [(ts(f'{day}T{t}'), float(v)) for t, v in (r.split() for r in rows.strip().splitlines())]


